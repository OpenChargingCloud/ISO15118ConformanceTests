using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Vanaheimr.V2G.Exi.SourceGenerator.Grammar;

namespace Vanaheimr.V2G.Exi.SourceGenerator.Emit;

/// <summary>
/// Produces C# source from a <see cref="SchemaPlan"/>.
/// One emitted file per schema, containing record types, enum types, and a
/// static codec class. The generated codec mirrors the structure of the
/// hand-written <c>SupportedAppProtocolCodec</c> so the AppProtocol bytes
/// are byte-equivalent.
/// </summary>
internal sealed class CodecEmitter
{
    private const string GeneratedNamespace = "Vanaheimr.V2G.AppProtocol.Generated";

    private readonly StringBuilder _sb = new();
    private readonly SchemaPlan _plan;
    private readonly HashSet<string> _emittedRecords = new(StringComparer.Ordinal);

    private CodecEmitter(SchemaPlan plan) { _plan = plan; }

    public static string Emit(SchemaPlan plan) => new CodecEmitter(plan).Run();

    private string Run()
    {
        _sb.AppendLine("// <auto-generated/>");
        _sb.AppendLine("// Generated by Vanaheimr.V2G.Exi.SourceGenerator. Do not edit by hand.");
        _sb.AppendLine("#nullable enable");
        _sb.AppendLine("using System;");
        _sb.AppendLine("using System.Collections.Generic;");
        _sb.AppendLine("using System.IO;");
        _sb.AppendLine("using Vanaheimr.V2G.Exi;");
        _sb.AppendLine();
        _sb.Append("namespace ").Append(GeneratedNamespace).AppendLine(";");
        _sb.AppendLine();

        EmitEnums();
        EmitRecords();
        EmitCodec();

        return _sb.ToString();
    }

    // -----------------------------------------------------------------------
    //  Enums
    // -----------------------------------------------------------------------

    private void EmitEnums()
    {
        foreach (var e in _plan.Enums)
        {
            _sb.Append("public enum ").Append(e.Name).AppendLine(" : byte");
            _sb.AppendLine("{");
            for (int i = 0; i < e.Members.Count; i++)
            {
                _sb.Append("    ").Append(e.Members[i]).Append(" = ").Append(i);
                _sb.AppendLine(i + 1 < e.Members.Count ? "," : "");
            }
            _sb.AppendLine("}");
            _sb.AppendLine();
        }
    }

    // -----------------------------------------------------------------------
    //  Records — emit dependencies first, deduplicated
    // -----------------------------------------------------------------------

    private void EmitRecords()
    {
        foreach (var sp in _plan.ComplexTypes.Values
                                  .OrderBy(s => DependencyDepth(s)))
        {
            EmitRecord(sp);
        }
    }

    private int DependencyDepth(SequencePlan sp)
    {
        int max = 0;
        foreach (var c in sp.Children)
        {
            if (c.Value is ValueEncoding.ComplexRef cr &&
                _plan.ComplexTypes.TryGetValue(cr.TypeName, out var inner))
            {
                max = Math.Max(max, 1 + DependencyDepth(inner));
            }
        }
        return max;
    }

    private void EmitRecord(SequencePlan sp)
    {
        if (!_emittedRecords.Add(sp.CSharpRecordName)) return;

        _sb.Append("public sealed record ").Append(sp.CSharpRecordName).AppendLine("(");

        for (int i = 0; i < sp.Children.Count; i++)
        {
            var c = sp.Children[i];
            string typeText = c.Shape switch
            {
                ChildShape.BoundedRepeating => $"IReadOnlyList<{c.CSharpType}>",
                ChildShape.OptionalSingle   => c.CSharpType + "?",
                _                           => c.CSharpType,
            };
            _sb.Append("    ").Append(typeText).Append(' ').Append(c.FieldName);
            _sb.AppendLine(i + 1 < sp.Children.Count ? "," : "");
        }
        _sb.AppendLine(");");
        _sb.AppendLine();
    }

    // -----------------------------------------------------------------------
    //  Codec
    // -----------------------------------------------------------------------

    private void EmitCodec()
    {
        _sb.AppendLine("public static class SupportedAppProtocolCodec");
        _sb.AppendLine("{");
        _sb.AppendLine("    public const byte ExiHeader = 0x80;");
        _sb.AppendLine();

        var globals = _plan.GlobalElements
                           .OrderBy(g => g.XsdName, StringComparer.Ordinal)
                           .ToList();
        int docBits = BitsForChoices(globals.Count);

        // Public encode entry points (one extension method per global element).
        for (int idx = 0; idx < globals.Count; idx++)
            EmitEncodeEntryPoint(globals[idx], idx, docBits);

        // DecodeAny dispatcher.
        EmitDecodeDispatcher(globals, docBits);

        // Per-complex-type encode/decode methods, deduplicated by record name.
        var seenComplex = new HashSet<string>(StringComparer.Ordinal);
        foreach (var sp in _plan.ComplexTypes.Values
                                  .OrderBy(s => s.CSharpRecordName, StringComparer.Ordinal))
        {
            if (!seenComplex.Add(sp.CSharpRecordName)) continue;
            EmitEncodeMethod(sp);
            EmitDecodeMethod(sp);
        }

        // Lex-index helpers, one block per enum.
        foreach (var e in _plan.Enums)
            EmitEnumLexHelpers(e);

        _sb.AppendLine("}");
    }

    private void EmitEncodeEntryPoint(GlobalElementPlan g, int idx, int docBits)
    {
        _sb.Append("    public static bool TryEncode(this ")
           .Append(g.CSharpTypeName)
           .AppendLine(" msg, Span<byte> dest, out int bytesWritten)");
        _sb.AppendLine("    {");
        _sb.AppendLine("        bytesWritten = 0;");
        _sb.AppendLine("        if (dest.Length < 1) return false;");
        _sb.AppendLine("        dest[0] = ExiHeader;");
        _sb.AppendLine("        var w = new BitWriter(dest[1..]);");
        if (docBits > 0)
            _sb.Append("        w.WriteBits(").Append(idx).Append(", ").Append(docBits).AppendLine(");");
        _sb.Append("        Encode_").Append(g.Body.CSharpRecordName).AppendLine("(ref w, msg);");
        _sb.AppendLine("        w.AlignToByte();");
        _sb.AppendLine("        bytesWritten = 1 + w.BytesWritten;");
        _sb.AppendLine("        return true;");
        _sb.AppendLine("    }");
        _sb.AppendLine();
    }

    private void EmitDecodeDispatcher(List<GlobalElementPlan> globals, int docBits)
    {
        _sb.AppendLine("    public static object DecodeAny(ReadOnlySpan<byte> src, out int bytesConsumed)");
        _sb.AppendLine("    {");
        _sb.AppendLine("        if (src.Length < 1 || src[0] != ExiHeader)");
        _sb.AppendLine("            throw new InvalidDataException(\"Invalid EXI header.\");");
        _sb.AppendLine("        var r = new BitReader(src[1..]);");

        if (docBits > 0)
        {
            _sb.Append("        uint sel = r.ReadBits(").Append(docBits).AppendLine(");");
            _sb.AppendLine("        object result = sel switch");
            _sb.AppendLine("        {");
            for (int idx = 0; idx < globals.Count; idx++)
            {
                _sb.Append("            ").Append(idx).Append("u => Decode_")
                   .Append(globals[idx].Body.CSharpRecordName).AppendLine("(ref r),");
            }
            _sb.AppendLine("            _ => throw new InvalidDataException($\"Unknown document index {sel}.\"),");
            _sb.AppendLine("        };");
        }
        else
        {
            _sb.Append("        object result = Decode_")
               .Append(globals[0].Body.CSharpRecordName).AppendLine("(ref r);");
        }

        _sb.AppendLine("        bytesConsumed = 1 + r.BytesConsumed;");
        _sb.AppendLine("        return result;");
        _sb.AppendLine("    }");
        _sb.AppendLine();
    }

    // -----------------------------------------------------------------------
    //  Encode_/Decode_<RecordName> per complex type
    // -----------------------------------------------------------------------

    private void EmitEncodeMethod(SequencePlan sp)
    {
        _sb.Append("    private static void Encode_").Append(sp.CSharpRecordName)
           .Append("(ref BitWriter w, ").Append(sp.CSharpRecordName).AppendLine(" msg)");
        _sb.AppendLine("    {");

        if (IsBoundedRepeating(sp, out var rep))
        {
            _sb.Append("        var list = msg.").Append(rep.FieldName).AppendLine(";");
            _sb.Append("        if (list.Count is < ").Append(Math.Max(1, sp.ListMin))
               .Append(" or > ").Append(sp.ListMax)
               .AppendLine(") throw new ArgumentOutOfRangeException(nameof(msg));");
            _sb.AppendLine("        for (int i = 0; i < list.Count; i++)");
            _sb.AppendLine("        {");
            _sb.AppendLine("            if (i > 0) w.WriteBits(0, 1);");
            EmitWriteValue(rep, "list[i]", "            ");
            _sb.AppendLine("        }");
            _sb.Append("        if (list.Count < ").Append(sp.ListMax).AppendLine(") w.WriteBits(1, 1);");
        }
        else
        {
            foreach (var c in sp.Children)
            {
                if (c.Shape == ChildShape.OptionalSingle)
                {
                    string presence = c.IsCSharpNullable
                        ? $"msg.{c.FieldName}.HasValue"
                        : $"msg.{c.FieldName} is not null";
                    string accessor = c.IsCSharpNullable
                        ? $"msg.{c.FieldName}!.Value"
                        : $"msg.{c.FieldName}!";
                    _sb.Append("        if (").Append(presence).AppendLine(")");
                    _sb.AppendLine("        {");
                    _sb.AppendLine("            w.WriteBits(0, 1);");
                    EmitWriteValue(c, accessor, "            ");
                    _sb.AppendLine("        }");
                    _sb.AppendLine("        else { w.WriteBits(1, 1); }");
                }
                else
                {
                    EmitWriteValue(c, $"msg.{c.FieldName}", "        ");
                }
            }
        }

        _sb.AppendLine("    }");
        _sb.AppendLine();
    }

    private void EmitDecodeMethod(SequencePlan sp)
    {
        _sb.Append("    private static ").Append(sp.CSharpRecordName)
           .Append(" Decode_").Append(sp.CSharpRecordName).AppendLine("(ref BitReader r)");
        _sb.AppendLine("    {");

        if (IsBoundedRepeating(sp, out var rep))
        {
            _sb.Append("        var list = new List<").Append(rep.CSharpType).AppendLine(">();");
            EmitReadValue(rep, "first", "        ", declare: true);
            _sb.AppendLine("        list.Add(first);");
            _sb.Append("        while (list.Count < ").Append(sp.ListMax).AppendLine(")");
            _sb.AppendLine("        {");
            _sb.AppendLine("            uint ec = r.ReadBits(1);");
            _sb.AppendLine("            if (ec == 1) break;");
            EmitReadValue(rep, "next", "            ", declare: true);
            _sb.AppendLine("            list.Add(next);");
            _sb.AppendLine("        }");
            _sb.Append("        return new ").Append(sp.CSharpRecordName).AppendLine("(list);");
        }
        else
        {
            var locals = new List<string>();
            foreach (var c in sp.Children)
            {
                string local = "_" + c.FieldName;
                locals.Add(local);

                if (c.Shape == ChildShape.OptionalSingle)
                {
                    _sb.Append("        ").Append(c.CSharpType).Append("? ").Append(local).AppendLine(" = default;");
                    _sb.AppendLine("        {");
                    _sb.AppendLine("            uint ec = r.ReadBits(1);");
                    _sb.AppendLine("            if (ec == 0)");
                    _sb.AppendLine("            {");
                    EmitReadValue(c, local, "                ", declare: false);
                    _sb.AppendLine("            }");
                    _sb.AppendLine("        }");
                }
                else
                {
                    EmitReadValue(c, local, "        ", declare: true);
                }
            }
            _sb.Append("        return new ").Append(sp.CSharpRecordName).Append('(')
               .Append(string.Join(", ", locals)).AppendLine(");");
        }

        _sb.AppendLine("    }");
        _sb.AppendLine();
    }

    private void EmitWriteValue(ChildPlan c, string accessor, string indent)
    {
        switch (c.Value)
        {
            case ValueEncoding.UnsignedInt:
                _sb.Append(indent).Append("ExiPrimitives.WriteUnsignedInteger(ref w, (ulong)")
                   .Append(accessor).AppendLine(");");
                break;
            case ValueEncoding.StringValue:
                _sb.Append(indent).Append("ExiPrimitives.WriteStringValue(ref w, ")
                   .Append(accessor).AppendLine(");");
                break;
            case ValueEncoding.NBitUnsigned nb when nb.Bias != 0:
                _sb.Append(indent).Append("w.WriteBits((uint)((long)")
                   .Append(accessor).Append(" - ").Append(nb.Bias).Append("), ")
                   .Append(nb.BitWidth).AppendLine(");");
                break;
            case ValueEncoding.NBitUnsigned nb:
                _sb.Append(indent).Append("w.WriteBits((uint)").Append(accessor)
                   .Append(", ").Append(nb.BitWidth).AppendLine(");");
                break;
            case ValueEncoding.EnumIndex ei:
                _sb.Append(indent).Append("w.WriteBits((uint)LexIndex_").Append(ei.EnumName)
                   .Append('(').Append(accessor).Append("), ").Append(ei.BitWidth).AppendLine(");");
                break;
            case ValueEncoding.ComplexRef cr:
                _sb.Append(indent).Append("Encode_").Append(cr.TypeName).Append("(ref w, ")
                   .Append(accessor).AppendLine(");");
                break;
        }
    }

    private void EmitReadValue(ChildPlan c, string local, string indent, bool declare)
    {
        _sb.Append(indent);
        if (declare) _sb.Append("var ").Append(local).Append(" = ");
        else         _sb.Append(local).Append(" = ");

        switch (c.Value)
        {
            case ValueEncoding.UnsignedInt:
                _sb.Append('(').Append(c.CSharpType)
                   .Append(")ExiPrimitives.ReadUnsignedInteger(ref r)");
                break;
            case ValueEncoding.StringValue:
                _sb.Append("ExiPrimitives.ReadStringValue(ref r)");
                break;
            case ValueEncoding.NBitUnsigned nb when nb.Bias != 0:
                _sb.Append('(').Append(c.CSharpType).Append(")((long)r.ReadBits(")
                   .Append(nb.BitWidth).Append(") + ").Append(nb.Bias).Append(')');
                break;
            case ValueEncoding.NBitUnsigned nb:
                _sb.Append('(').Append(c.CSharpType).Append(")r.ReadBits(").Append(nb.BitWidth).Append(')');
                break;
            case ValueEncoding.EnumIndex ei:
                _sb.Append("FromLexIndex_").Append(ei.EnumName)
                   .Append("(r.ReadBits(").Append(ei.BitWidth).Append("))");
                break;
            case ValueEncoding.ComplexRef cr:
                _sb.Append("Decode_").Append(cr.TypeName).Append("(ref r)");
                break;
        }
        _sb.AppendLine(";");
    }

    // -----------------------------------------------------------------------
    //  Enum lex-index helpers
    // -----------------------------------------------------------------------

    private void EmitEnumLexHelpers(EnumPlan e)
    {
        // (declaration name, lex index)
        var lexSorted = e.Members
            .Select((name, declIdx) => (name, declIdx))
            .OrderBy(t => t.name, StringComparer.Ordinal)
            .ToList();

        _sb.Append("    private static int LexIndex_").Append(e.Name)
           .Append('(').Append(e.Name).AppendLine(" v) => v switch");
        _sb.AppendLine("    {");
        for (int lex = 0; lex < lexSorted.Count; lex++)
        {
            _sb.Append("        ").Append(e.Name).Append('.').Append(lexSorted[lex].name)
               .Append(" => ").Append(lex).AppendLine(",");
        }
        _sb.AppendLine("        _ => throw new ArgumentOutOfRangeException(nameof(v)),");
        _sb.AppendLine("    };");
        _sb.AppendLine();

        _sb.Append("    private static ").Append(e.Name)
           .Append(" FromLexIndex_").Append(e.Name).AppendLine("(uint idx) => idx switch");
        _sb.AppendLine("    {");
        for (int lex = 0; lex < lexSorted.Count; lex++)
        {
            _sb.Append("        ").Append(lex).Append("u => ").Append(e.Name)
               .Append('.').Append(lexSorted[lex].name).AppendLine(",");
        }
        _sb.AppendLine("        _ => throw new InvalidDataException($\"Reserved enum index: {idx}\"),");
        _sb.AppendLine("    };");
        _sb.AppendLine();
    }

    // -----------------------------------------------------------------------
    //  Helpers
    // -----------------------------------------------------------------------

    private static bool IsBoundedRepeating(SequencePlan sp, out ChildPlan rep)
    {
        if (sp.Children.Count == 1 && sp.Children[0].Shape == ChildShape.BoundedRepeating)
        {
            rep = sp.Children[0];
            return true;
        }
        rep = default!;
        return false;
    }

    private static int BitsForChoices(int n)
    {
        if (n <= 1) return 0;
        int bits = 0;
        int v = n - 1;
        while (v > 0) { bits++; v >>= 1; }
        return bits;
    }
}
